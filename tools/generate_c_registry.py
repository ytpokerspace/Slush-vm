#!/usr/bin/env python3
"""Generate the C demo registry table from the JSON vocabulary/alias/contracts."""
import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

def read_json(path):
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise ValueError(f"{path.relative_to(ROOT)}: {exc}") from exc

def cstr(value):
    # JSON string escaping is compatible with C string literals for these ASCII/Unicode strings.
    return json.dumps(value, ensure_ascii=False)

def render():
    vocab = read_json(ROOT / "registry/vocabulary.json")
    aliases_doc = read_json(ROOT / "registry/workflow_aliases.json")
    demo = read_json(ROOT / "examples/demo_capabilities.json")
    vocab_by_id = {x["id"]: x for x in vocab.get("entries", [])}
    demo_by_key = {(x["id"], x["version"]): x for x in demo.get("capabilities", [])}
    aliases = aliases_doc.get("aliases", [])
    seen = set()
    rows = []
    for alias in aliases:
        key = (alias.get("symbol"), alias.get("namespace"))
        if key in seen:
            raise ValueError(f"ambiguous alias in JSON: {key!r}")
        seen.add(key)
        entry = vocab_by_id.get(alias.get("vocabulary_id"))
        if not entry or entry.get("symbol") != alias.get("symbol"):
            raise ValueError(f"alias {key!r} does not match vocabulary_id {alias.get('vocabulary_id')!r}")
        cap = demo_by_key.get((alias.get("capability_id"), alias.get("version")))
        if not cap:
            raise ValueError(f"alias {key!r} has no exact demo capability contract")
        if cap.get("status") != "tested" or cap.get("tests", {}).get("status") not in ("passed", "passed_with_notes"):
            raise ValueError(f"alias {key!r} points to an unverified demo capability")
        if cap.get("inputs") != {"text": "STR"}:
            raise ValueError(f"unsupported C demo input contract for {cap.get('id')}")
        if cap.get("id") == "text.normalize" and cap.get("outputs") != {"text": "STR"}:
            raise ValueError("text.normalize output contract mismatch")
        if cap.get("id") == "text.word_count" and cap.get("outputs") != {"count": "NUM"}:
            raise ValueError("text.word_count output contract mismatch")
        rows.append((alias, cap))
    if not rows:
        raise ValueError("no aliases found; refusing to generate an empty registry")
    lines = [
        "/* Generated by tools/generate_c_registry.py; do not edit by hand. */",
        "#ifndef SHUSH_GENERATED_REGISTRY_H",
        "#define SHUSH_GENERATED_REGISTRY_H",
        "#define SHUSH_GENERATED_CAPABILITY_COUNT " + str(len(rows)),
        "#define SHUSH_GENERATED_CAPABILITY_ROWS \\",
    ]
    for i, (alias, cap) in enumerate(rows):
        handler = "normalize" if cap["id"] == "text.normalize" else "word_count"
        row = "    {" + ", ".join(cstr(x) for x in (
            cap["id"], cap["version"], cap["status"], "STR",
            "STR" if handler == "normalize" else "NUM",
            "capability.execute", handler, alias["symbol"], alias["namespace"]
        )) + "}"
        if i != len(rows) - 1:
            row += ", \\"
        lines.append(row)
    lines.extend(["#endif", ""])
    return "\n".join(lines)

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if generated header is stale")
    args = parser.parse_args()
    destination = ROOT / "c/generated_registry.h"
    try:
        output = render()
    except ValueError as exc:
        print(f"REGISTRY_GENERATION_ERROR: {exc}", file=sys.stderr)
        return 2
    if args.check:
        try:
            existing = destination.read_text(encoding="utf-8")
        except OSError:
            existing = None
        if existing != output:
            print("Generated C registry is stale; run python tools/generate_c_registry.py", file=sys.stderr)
            return 1
        print("OK: generated C registry matches JSON sources")
        return 0
    destination.write_text(output, encoding="utf-8")
    print(f"Wrote {destination.relative_to(ROOT)}")
    return 0

if __name__ == "__main__":
    raise SystemExit(main())
